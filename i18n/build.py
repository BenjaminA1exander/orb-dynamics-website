#!/usr/bin/env python3
"""Build the translated pages from index.html and i18n/<lang>.json.

index.html stays the hand-edited English source. Each <lang>.json maps an exact
English fragment of it to a translation. The build fails if a fragment is no
longer in index.html, if language files disagree on their keys, or if English
text is left on a translated page, so a copy change cannot silently go stale.

    py -3 i18n/build.py [YYYY-MM-DD]     (date = sitemap lastmod, default today)

To add a language: copy es.json to <code>.json, translate it, run this script.
"""
import datetime
import html
import html.parser
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = "https://orbdynamics.eu/"
ENGLISH = {"code": "en", "name": "English", "locale": "en_GB", "language_label": "Language"}
# Proper nouns and footnote marks that read the same on every page.
KEEP = {"ORB Dynamics", "YES!Delft", "TU Delft", "© 2026 ORB Dynamics", "Ben O’Regan", "George Beacom", "&", "0",
        "1", "2", "3", "DJI", "DJI Matrice 350 RTK", "Quantum Systems", "Quantum Systems Vector AI", "Airbus",
        "Airbus H125"}
VIDEO_TITLE = "Six ORB airships patrol Ourense, Spain, and detect two wildfires"
VIDEO_DESCRIPTION = ("Illustrative simulation: six autonomous hydrogen airships patrolling Ourense, Spain, "
                     "on real terrain, detecting two wildfires.")


def block(text, name, body):
    new = f"<!-- i18n:{name} -->\n{body}\n<!-- /i18n:{name} -->"
    out, n = re.subn(rf"<!-- i18n:{name} -->.*?<!-- /i18n:{name} -->", lambda _: new, text, flags=re.S)
    if n != 1:
        sys.exit(f"marker i18n:{name} not found exactly once in index.html")
    return out


def url(lang):
    return SITE if lang["code"] == "en" else f"{SITE}{lang['code']}/"


def path(lang):
    return "/" if lang["code"] == "en" else f"/{lang['code']}/"


def alternates(langs):
    lines = [f'<link rel="alternate" hreflang="{l["code"]}" href="{url(l)}">' for l in langs]
    lines.append(f'<link rel="alternate" hreflang="x-default" href="{SITE}">')
    return "\n".join(lines)


def og_locales(langs, current):
    return "\n".join(f'<meta property="og:locale:alternate" content="{l["locale"]}">'
                     for l in langs if l is not current)


def switcher(langs, current):
    items = []
    for l in langs:
        mark = ' aria-current="true"' if l is current else ""
        items.append(f'          <li><a href="{path(l)}" lang="{l["code"]}" hreflang="{l["code"]}"{mark}>{l["name"]}</a></li>')
    label = current["language_label"]
    return (f'      <details class="lang">\n'
            f'        <summary aria-label="{label}" title="{label}">{current["code"].upper()}</summary>\n'
            f'        <ul>\n' + "\n".join(items) + '\n        </ul>\n'
            f'      </details>')


def with_shared_blocks(text, langs, current):
    text = block(text, "alternates", alternates(langs))
    text = block(text, "og", og_locales(langs, current))
    text = block(text, "switcher", switcher(langs, current))
    codes = ", ".join(f'"{l["code"]}"' for l in langs)
    return re.sub(r'"inLanguage": (".*?"|\[.*?\])', f'"inLanguage": [{codes}]', text, count=1)


def translate(source, strings, lang):
    missing = [k for k in strings if k not in source]
    if missing:
        sys.exit(f"{lang['code']}: not in index.html (English changed? update every language):\n  "
                 + "\n  ".join(missing))
    # Longest first, so a sentence is replaced before any phrase inside it. Placeholders stop a
    # translation being re-translated by a later, shorter key.
    text, done = source, []
    for key in sorted(strings, key=len, reverse=True):
        text = text.replace(key, f"\0{len(done)}\0")
        done.append(strings[key])
    text = re.sub(r"\0(\d+)\0", lambda m: done[int(m.group(1))], text)

    page = url(lang)
    text = text.replace('<html lang="en">', f'<html lang="{lang["code"]}">', 1)
    text = text.replace(f'<link rel="canonical" href="{SITE}">', f'<link rel="canonical" href="{page}">', 1)
    text = text.replace(f'<meta property="og:url" content="{SITE}">', f'<meta property="og:url" content="{page}">', 1)
    text = text.replace('<meta property="og:locale" content="en_GB">',
                        f'<meta property="og:locale" content="{lang["locale"]}">', 1)
    text = text.replace('<a class="logo" href="/">', f'<a class="logo" href="{path(lang)}">', 1)
    # The page sits one folder down.
    text = re.sub(r'\b(src|poster)="img/', r'\1="/img/', text)
    text = text.replace("'img/spin/az'", "'/img/spin/az'")
    banner = "<!-- GENERATED by i18n/build.py. Edit index.html and i18n/*.json, not this file. -->\n"
    return text.replace("<!doctype html>\n", "<!doctype html>\n" + banner, 1)


class Visible(html.parser.HTMLParser):
    """Body text plus the alt, aria-label and title a visitor or screen reader meets."""

    def __init__(self):
        super().__init__()
        self.found, self.skip, self.in_body = set(), 0, False

    def handle_starttag(self, tag, attrs):
        if tag == "body":
            self.in_body = True
        if tag in ("script", "style"):
            self.skip += 1
        if self.in_body:
            self.found.update(v.strip() for k, v in attrs if k in ("alt", "aria-label", "title") and v)

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self.skip -= 1

    def handle_data(self, data):
        if self.in_body and not self.skip and data.strip():
            self.found.add(data.strip())


def visible(text):
    parser = Visible()
    parser.feed(text)
    return parser.found


def check(lang, page, english, strings, langs):
    json.loads(re.search(r'<script type="application/ld\+json">(.*?)</script>', page, re.S).group(1))
    # A value equal to the English (Dutch "Contact") was chosen, not forgotten.
    deliberate = {html.unescape(piece).strip() for v in strings.values() for piece in re.split(r"[<>]", v)}
    menu = {l["name"] for l in langs}
    left = (visible(page) & visible(english)) - KEEP - deliberate - menu
    if left:
        sys.exit(f"{lang['code']}: English left on the page:\n  " + "\n  ".join(sorted(left)))


def sitemap(langs, translations, date):
    links = "\n".join(f'    <xhtml:link rel="alternate" hreflang="{l["code"]}" href="{url(l)}"/>' for l in langs)
    links += f'\n    <xhtml:link rel="alternate" hreflang="x-default" href="{SITE}"/>'
    entries = []
    for l in langs:
        strings = translations.get(l["code"], {})
        entries.append(f"""  <url>
    <loc>{url(l)}</loc>
    <lastmod>{date}</lastmod>
{links}
    <image:image><image:loc>{SITE}img/spin/az080.jpg</image:loc></image:image>
    <video:video>
      <video:thumbnail_loc>{SITE}img/orb-sim-poster.jpg</video:thumbnail_loc>
      <video:title>{strings.get(VIDEO_TITLE, VIDEO_TITLE)}</video:title>
      <video:description>{strings.get(VIDEO_DESCRIPTION, VIDEO_DESCRIPTION)}</video:description>
      <video:content_loc>{SITE}img/orb-sim.mp4</video:content_loc>
      <video:duration>48</video:duration>
    </video:video>
  </url>""")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n'
            '        xmlns:xhtml="http://www.w3.org/1999/xhtml"\n'
            '        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1"\n'
            '        xmlns:video="http://www.google.com/schemas/sitemap-video/1.1">\n'
            + "\n".join(entries) + "\n</urlset>\n")


def llms(text, langs):
    lines = "\n".join(f"- {l['name']}: {url(l)}" for l in langs)
    return text.split("## Languages")[0].rstrip() + f"\n\n## Languages\n\n{lines}\n"


def read(file):
    return file.read_bytes().decode("utf-8")


def write(file, text):
    file.parent.mkdir(exist_ok=True)
    file.write_bytes(text.encode("utf-8"))


def main():
    date = sys.argv[1] if len(sys.argv) > 1 else datetime.date.today().isoformat()
    langs, translations = [ENGLISH], {}
    for file in sorted((ROOT / "i18n").glob("*.json")):
        data = json.loads(read(file))
        langs.append({"code": file.stem, **data["meta"]})
        translations[file.stem] = data["strings"]
    langs.sort(key=lambda l: l["name"].casefold())

    reference = set(next(iter(translations.values())))
    for code, strings in translations.items():
        if set(strings) != reference:
            sys.exit(f"{code}: keys differ from the other languages: {sorted(set(strings) ^ reference)}")

    english = with_shared_blocks(read(ROOT / "index.html"), langs, ENGLISH)
    write(ROOT / "index.html", english)

    for lang in langs:
        if lang is ENGLISH:
            continue
        strings = translations[lang["code"]]
        page = translate(with_shared_blocks(english, langs, lang), strings, lang)
        check(lang, page, english, strings, langs)
        write(ROOT / lang["code"] / "index.html", page)
        print(f"{lang['code']}: {len(strings)} strings -> {lang['code']}/index.html")

    write(ROOT / "sitemap.xml", sitemap(langs, translations, date))
    write(ROOT / "llms.txt", llms(read(ROOT / "llms.txt"), langs))


if __name__ == "__main__":
    main()
